"""Module de calcul mathématiques."""


def add(a, b) -> int:
    """Fonction qui calcul a+b correctement!.

    Args:
        a (int) : a
        b (int) : b

    Returns:
        c(int) : c

    """
    return int(a + b)


def sub(a, b) -> int:
    """Fonction qui calcul a-b correctement!.

    Args:
        a (int) : a
        b (int) : b

    Returns:
        c(int) : c

    """
    return int(a - b)


def square(a) -> int:
    """Fonction qui calcul a*2 correctement!.

    Args:
        a (int) : a

    Returns:
        c(int) : c

    """
    return int(a * a)
